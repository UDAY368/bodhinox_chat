-- Instagram message templates: a workspace's saved card (generic template,
-- 1-10 cards) and button (text + 1-3 buttons) messages that members send from
-- the inbox inside Instagram's messaging window. Meta has no approved templates
-- for Instagram; these are Bodhinox's own saved layouts, checked against
-- Instagram's limits by src/lib/instagram/message-templates.ts on every write
-- and again on every send.
--
-- payload (validated by the app, never trusted on send):
--   kind 'cards':  { "cards": [{ title, subtitle?, imageUrl?, defaultUrl?, buttons?: [...] }] }
--   kind 'button': { "text": "...", "buttons": [...] }
--   a button is { type:'web_url', title, url } or { type:'postback', title, payload }
--   (postback payloads are generated by the app as 'reply:<title>').
--
-- Additive: a new table with forced row-level security. Members (agent and
-- above) write; viewers and the worker read.
SET LOCAL lock_timeout = '5s';

CREATE TABLE instagram_message_templates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id uuid NOT NULL DEFAULT NULLIF(current_setting('app.account_id', true),'')::uuid
    REFERENCES accounts(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80 AND name = btrim(name)),
  kind text NOT NULL CHECK (kind IN ('cards','button')),
  payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object' AND octet_length(payload::text) <= 20000),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account_id, id)
);
CREATE UNIQUE INDEX instagram_message_templates_name_idx ON instagram_message_templates(account_id, lower(name));

ALTER TABLE instagram_message_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_message_templates FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_read ON instagram_message_templates FOR SELECT TO bodhinox_app, bodhinox_worker
  USING (account_id = app_account_id());
CREATE POLICY tenant_write ON instagram_message_templates FOR ALL TO bodhinox_app
  USING (account_id = app_account_id() AND app_write_allowed('agent'))
  WITH CHECK (account_id = app_account_id() AND app_write_allowed('agent'));
GRANT SELECT, INSERT, UPDATE, DELETE ON instagram_message_templates TO bodhinox_app;
GRANT SELECT ON instagram_message_templates TO bodhinox_worker;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON instagram_message_templates
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
